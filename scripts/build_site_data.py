#!/usr/bin/env python3
"""Build the static data bundle used by preview.html."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLAIMS_CSV = ROOT / "results" / "tables" / "claims.csv"
OUT = ROOT / "assets" / "site-data.js"

VERDICT_LABELS = {
    "supported": "Supported",
    "partially_supported": "Partially supported",
    "unsupported": "Unsupported",
    "not_verifiable": "Not verifiable",
}


def main() -> None:
    with CLAIMS_CSV.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    claims = []
    for row in rows:
        sources = [s.strip() for s in row.get("sources_joined", "").split(";") if s.strip()]
        claims.append(
            {
                "id": row["id"],
                "category": row["category"],
                "claim": row["transcript_claim"],
                "verdict": row["verdict"],
                "verdictLabel": VERDICT_LABELS[row["verdict"]],
                "confidence": row["confidence"],
                "evidence": row["evidence"],
                "notes": row["notes"],
                "sourceCount": len(sources),
            }
        )

    verdict_counts = {key: 0 for key in VERDICT_LABELS}
    for claim in claims:
        verdict_counts[claim["verdict"]] += 1

    payload = {
        "generatedFrom": "results/tables/claims.csv",
        "total": len(claims),
        "verdictCounts": verdict_counts,
        "claims": claims,
    }
    OUT.write_text(
        "/* Generated by scripts/build_site_data.py. Do not edit by hand. */\n"
        "window.EVIDENCE_DATA = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(claims)} claims)")


if __name__ == "__main__":
    main()
